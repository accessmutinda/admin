export function seededAssessment(name: string, review: string): PlanAssessment {
  return {
    id: 'demo-assessment-' + name.toLowerCase().replace(/[^a-z]+/g, '-'),
    name,
    section: ASSESSMENT_AREAS[name],
    findings: `Fictional ${name.toLowerCase()} assessment example. Review the structured findings with the service user and relevant professional.`,
    action:
      'Follow the current assessed instructions, record observations and report changes to the duty supervisor.',
    review,
    status: 'In progress',
    fields: Object.fromEntries(
      (ASSESSMENT_FIELDS[name] || []).map(([key], i) => [
        key,
        EXAMPLES[name]?.[i] || 'Confirm at review.',
      ]),
    ),
  };
}
