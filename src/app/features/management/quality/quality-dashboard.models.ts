export interface QualityMetric {
  label: string;
  value: string;
  change: string;
  note: string;
  icon: string;
  tone: string;
}
export interface QualitySeries {
  label: string;
  values: number[];
  color: string;
}
export interface QualityPanel {
  title: string;
  icon: string;
  kind:
    | 'table'
    | 'chart'
    | 'heatmap'
    | 'radar'
    | 'donut'
    | 'gallery'
    | 'tiles'
    | 'progress'
    | 'timeline'
    | 'funnel'
    | 'checklist';
  columns?: string[];
  rows?: string[][];
  series?: QualitySeries[];
  labels?: string[];
  wide?: boolean;
  tall?: boolean;
  note?: string;
  min?: number;
  max?: number;
  forecast?: boolean;
}
export interface QualityDashboard {
  slug: string;
  title: string;
  subtitle: string;
  icon: string;
  metrics: QualityMetric[];
  panels: QualityPanel[];
}
const m = (
  label: string,
  value: string,
  change: string,
  icon: string,
  tone = 'green',
  note = 'vs last month',
): QualityMetric => ({ label, value, change, icon, tone, note });
const table = (
  title: string,
  icon: string,
  columns: string[],
  rows: string[][],
  extra: Partial<QualityPanel> = {},
): QualityPanel => ({ title, icon, kind: 'table', columns, rows, ...extra });
const tiles = (
  title: string,
  rows: string[][],
  extra: Partial<QualityPanel> = {},
): QualityPanel => ({ title, icon: 'groups', kind: 'tiles', rows, ...extra });
const trend = (
  title: string,
  names: string[],
  values: number[][],
  extra: Partial<QualityPanel> = {},
): QualityPanel => ({
  title,
  icon: 'monitoring',
  kind: 'chart',
  series: names.map((label, i) => ({
    label,
    values: values[i],
    color: extra.forecast
      ? i === 1
        ? '#087cf0'
        : title.startsWith('Compliance')
          ? '#f23373'
          : title.startsWith('Staffing')
            ? '#9434ed'
            : '#ff8c29'
      : ['#13aa80', '#087cf0', '#ff8c29', '#f20b79'][i],
  })),
  min: 60,
  max: 100,
  ...extra,
});
